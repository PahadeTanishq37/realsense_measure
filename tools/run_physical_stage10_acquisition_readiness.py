#!/usr/bin/env python3
"""
tools/run_physical_stage10_acquisition_readiness.py
===================================================
Problem 4 — Stage 10: Physical Data Acquisition Readiness & Capture-Only Workflow.

Executes:
1. Generates formal JSON Schema for capture session manifests.
2. Generates example manifest with clearly marked non-physical placeholders.
3. Generates practical physical capture checklist for operators.
4. Generates capture-only CLI guide and documentation.
5. Audits existing physical capture (body_capture_01) without modifying raw_captures/.
6. Generates known limitations and physical validation requirements.
7. Emits stage10_report.md and stage10_test_results.json.

All outputs are saved strictly under stage10_acquisition_readiness_output/.
"""

from __future__ import annotations

import argparse
import json
import logging
from pathlib import Path
import sys

# Configure python path to access repository modules
SCRIPT_DIR = Path(__file__).resolve().parent
REPO_ROOT = SCRIPT_DIR.parent
PACKAGE_DIR = REPO_ROOT / "realsense_measure"
for p in [str(REPO_ROOT), str(PACKAGE_DIR)]:
    if p not in sys.path:
        sys.path.insert(0, p)

from body.capture_session import (
    CaptureQualityChecker,
    CaptureSessionManifest,
    Stage10DeliverablesGenerator,
)
from camera.recording import load_raw_capture

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(name)s: %(message)s",
)
logger = logging.getLogger("run_physical_stage10")


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Stage 10: Physical Data Acquisition Readiness"
    )
    parser.add_argument(
        "--raw-dir",
        type=Path,
        default=Path("raw_captures/body_capture_01"),
        help="Path to physical raw capture directory for read-only audit (default: raw_captures/body_capture_01)",
    )
    parser.add_argument(
        "--out-dir",
        type=Path,
        default=Path("stage10_acquisition_readiness_output"),
        help="Target output directory (default: stage10_acquisition_readiness_output)",
    )

    args = parser.parse_args()

    logger.info("============================================================")
    logger.info("  Problem 4 — Stage 10: Acquisition Readiness & Capture-Only")
    logger.info("============================================================")
    logger.info(f"  Audit raw directory (READ-ONLY): {args.raw_dir}")
    logger.info(f"  Output directory:                {args.out_dir}")

    args.out_dir.mkdir(parents=True, exist_ok=True)

    # 1. Read-only audit of existing capture
    existing_manifest = None
    if args.raw_dir.exists():
        logger.info(f"Performing read-only audit of {args.raw_dir}...")
        frames = load_raw_capture(args.raw_dir)
        first_frame = frames[0] if frames else None
        intr_wh = (first_frame.intrinsics.width, first_frame.intrinsics.height) if first_frame else (1280, 720)

        pre_diag, warnings, failures = CaptureQualityChecker.evaluate_pre_save(
            frames,
            expected_yaw_stops=4,
            intrinsics_wh=intr_wh,
        )
        file_entries, post_diag = CaptureQualityChecker.evaluate_post_save(args.raw_dir)

        per_frame_stats = [
            CaptureQualityChecker.compute_depth_stats(f.depth_m)
            for f in frames if getattr(f, "depth_m", None) is not None
        ]

        existing_manifest = CaptureSessionManifest(
            capture_id=args.raw_dir.name,
            session_id=f"SESS_{args.raw_dir.name}",
            subject_id="SUBJ_01",
            operator_id="OPERATOR_01",
            config_id="CONFIG_D214_H100_Y4_R720",
            repeat_index=1,
            camera_to_subject_distance_m=2.14,
            camera_height_m=1.00,
            camera_pitch_tilt_deg=0.0,
            nominal_yaw_stops=[0.0, 90.0, 180.0, 270.0],
            capture_mode="capture_only",
            frames_captured=len(frames),
            expected_frames=4,
            depth_statistics_overall=per_frame_stats[0] if per_frame_stats else None,
            per_frame_depth_statistics=per_frame_stats,
            quality_diagnostics=pre_diag + post_diag,
            warnings=warnings,
            failures=failures,
            file_manifest=file_entries,
            notes="Read-only audit manifest of body_capture_01 generated by Stage 10.",
        )
        # Save audited manifest inside stage10_acquisition_readiness_output, NEVER in raw_captures/
        manifest_save_path = args.out_dir / "body_capture_01_manifest.json"
        existing_manifest.save(manifest_save_path)
        logger.info(f"Saved read-only audited manifest to {manifest_save_path}")

    # 2. Generate all Stage 10 deliverables
    generator = Stage10DeliverablesGenerator(output_dir=args.out_dir)
    res = generator.generate_all(existing_manifest)

    logger.info("------------------------------------------------------------")
    logger.info("Stage 10 Acquisition Readiness Generation Complete:")
    for k, v in res["artifacts"].items():
        logger.info(f"  {k}: {v}")
    logger.info("============================================================")
    return 0


if __name__ == "__main__":
    sys.exit(main())
